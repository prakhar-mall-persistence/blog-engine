#!/usr/bin/env node
// Build the public, read-only GitHub Pages site from locally generated previews.
// The interactive engine remains a private/local service; no credentials or API
// controls are shipped in this static output.
import { cp, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'output');
const SITE = join(ROOT, 'site');

if (!existsSync(OUT)) throw new Error('No generated previews found. Run the blog engine first.');

const files = (await readdir(OUT)).filter((file) => /^post-.+\.preview\.html$/.test(file));
const posts = await Promise.all(files.map(async (file) => {
  const slug = file.slice(5, -'.preview.html'.length);
  const recordPath = join(OUT, `post-${slug}.json`);
  const record = existsSync(recordPath) ? JSON.parse(await readFile(recordPath, 'utf8')) : {};
  return { slug, title: record.post?.title ?? slug, description: record.post?.description ?? '', date: record.post?.date ?? '', category: record.post?.category ?? 'Article', readTime: record.post?.readTime ?? '' };
}));
posts.sort((a, b) => a.title.localeCompare(b.title));

await rm(SITE, { recursive: true, force: true });
await mkdir(join(SITE, 'preview'), { recursive: true });
for (const post of posts) await cp(join(OUT, `post-${post.slug}.preview.html`), join(SITE, 'preview', `${post.slug}.html`));

const escape = (text) => String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const cards = posts.map((post) => `<a class="card" href="./preview/${encodeURIComponent(post.slug)}.html">
  <span class="meta">${escape(post.category)}${post.readTime ? ` · ${escape(post.readTime)}` : ''}</span>
  <h2>${escape(post.title)}</h2><p>${escape(post.description)}</p>
  <span class="open">Read preview →</span>
</a>`).join('\n');

await writeFile(join(SITE, 'index.html'), `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Persistence Blog Previews</title><meta name="description" content="Read-only previews generated by the Persistence Blog Engine.">
<style>
  :root{--ink:#0a0a0a;--muted:#65636d;--line:#e8e7ed;--purple:#5925dc;--tint:#f4f1ff}*{box-sizing:border-box}body{margin:0;background:#fff;color:var(--ink);font-family:Manrope,ui-sans-serif,system-ui,sans-serif}header{border-bottom:1px solid var(--line);padding:68px 24px 52px;background:linear-gradient(135deg,#fff 20%,var(--tint))}.wrap{max-width:1080px;margin:auto}.eyebrow{font-size:12px;letter-spacing:.12em;font-weight:800;color:var(--purple);text-transform:uppercase}h1{font-size:clamp(38px,6vw,66px);letter-spacing:-.05em;line-height:1.02;margin:12px 0 16px}.intro{max-width:600px;color:var(--muted);font-size:18px;line-height:1.55}main{padding:42px 24px 76px}.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(285px,1fr));gap:16px}.card{color:inherit;text-decoration:none;border:1px solid var(--line);border-radius:18px;padding:22px;min-height:230px;display:flex;flex-direction:column;transition:.18s}.card:hover{border-color:var(--purple);box-shadow:0 8px 24px #5925dc14;transform:translateY(-2px)}.meta{font-size:12px;font-weight:700;letter-spacing:.08em;text-transform:uppercase;color:var(--purple)}h2{font-size:21px;line-height:1.2;letter-spacing:-.025em;margin:13px 0 10px}p{color:var(--muted);font-size:14px;line-height:1.55;margin:0}.open{font-size:14px;font-weight:700;color:var(--purple);margin-top:auto;padding-top:20px}.note{margin-top:34px;color:var(--muted);font-size:13px}</style></head><body>
<header><div class="wrap"><div class="eyebrow">Persistence</div><h1>Blog previews</h1><p class="intro">A read-only collection of articles generated by the Persistence Blog Engine. Drafting, approvals, and publishing stay in the private engine.</p></div></header>
<main class="wrap"><div class="grid">${cards}</div><p class="note">${posts.length} article${posts.length === 1 ? '' : 's'} available.</p></main></body></html>`);
console.log(`Built ${posts.length} public previews in ${SITE}`);
